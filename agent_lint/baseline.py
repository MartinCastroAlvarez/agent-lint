"""The committed baseline: findings that existed when the gate was adopted.

The file is plain, sorted, deterministic JSON so that a reviewer sees in
the diff exactly which entries a change removes (a ratchet) or adds (a
loosening, which the ``baseline`` guard rejects).
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from agent_lint.config import BASELINE_FILE
from agent_lint.models import Finding
from agent_lint.paths import MAX_READ_BYTES
from agent_lint.paths import read_text
from agent_lint.paths import safe_join

SCHEMA = 1


class BaselineError(ValueError):
    """The baseline file is malformed."""


@dataclass(slots=True)
class Baseline:
    entries: dict[str, Finding]

    @classmethod
    def empty(cls) -> Baseline:
        return cls({})

    @classmethod
    def from_findings(cls, findings: Iterable[Finding]) -> Baseline:
        return cls({f.fingerprint: _entry(f) for f in findings})

    def __len__(self) -> int:
        return len(self.entries)

    def without(self, fingerprints: Iterable[str]) -> Baseline:
        drop = set(fingerprints)
        return Baseline({k: v for k, v in self.entries.items() if k not in drop})

    def dumps(self) -> str:
        items = sorted(self.entries.values(), key=lambda f: (f.path, f.tool, f.rule, f.fingerprint))
        doc = {
            "schema": SCHEMA,
            "tool": "agent-lint",
            "note": "Generated by `agent-lint init`; shrinks with `agent-lint ratchet`. "
            "Never add entries by hand.",
            "findings": [
                {
                    "fingerprint": f.fingerprint,
                    "tool": f.tool,
                    "rule": f.rule,
                    "path": f.path,
                    "message": f.message,
                }
                for f in items
            ],
        }
        return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def _entry(f: Finding) -> Finding:
    return Finding(f.tool, f.rule, f.path, 0, 0, f.message[:500], f.severity, f.fingerprint)


def _str(item: dict[str, Any], key: str) -> str:
    value = item.get(key)
    if not isinstance(value, str) or not value:
        raise BaselineError(f"baseline entry is missing {key!r}")
    return value


def loads(text: str) -> Baseline:
    if len(text) > MAX_READ_BYTES * 10:
        raise BaselineError("baseline is too large")
    try:
        doc = json.loads(text)
    except json.JSONDecodeError as exc:
        raise BaselineError(f"baseline is not valid JSON: {exc}") from exc
    if not isinstance(doc, dict) or doc.get("schema") != SCHEMA:
        raise BaselineError(f"unsupported baseline schema (expected {SCHEMA})")
    raw = doc.get("findings")
    if not isinstance(raw, list):
        raise BaselineError("baseline 'findings' must be a list")
    entries: dict[str, Finding] = {}
    for item in raw:
        if not isinstance(item, dict):
            raise BaselineError("baseline entries must be objects")
        message = item.get("message", "")
        f = Finding(
            tool=_str(item, "tool"),
            rule=_str(item, "rule"),
            path=_str(item, "path"),
            line=0,
            column=0,
            message=message if isinstance(message, str) else "",
            fingerprint=_str(item, "fingerprint"),
        )
        entries[f.fingerprint] = f
    return Baseline(entries)


def load(root: Path) -> Baseline | None:
    """The project's baseline, or ``None`` when it has not been initialised."""
    full = safe_join(root, BASELINE_FILE)
    if full is None or not full.exists():
        return None
    text = read_text(root, BASELINE_FILE, limit=MAX_READ_BYTES * 10)
    if text is None:
        raise BaselineError(f"{BASELINE_FILE} is unreadable")
    return loads(text)


def save(root: Path, baseline: Baseline) -> Path:
    full = safe_join(root, BASELINE_FILE)
    if full is None:
        raise BaselineError(f"refusing to write {BASELINE_FILE} outside the project")
    if full.is_symlink():
        raise BaselineError(f"refusing to write through a symlink: {BASELINE_FILE}")
    full.parent.mkdir(parents=True, exist_ok=True)
    tmp = full.with_suffix(".json.tmp")
    tmp.write_text(baseline.dumps(), encoding="utf-8")
    tmp.replace(full)
    return full
